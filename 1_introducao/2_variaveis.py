# variaveis sao um espaco na memoria 
# do computador que guardam um valor

nome = "Pedro" # tipo STRING, texto
idade = 20 # tipo INT, numeros inteiro
altura = 1.70 # tipo FLOAT, numeros de ponto flutuante
inf = True # tipo BOOLEAN, verdadeiro ou falso



print(nome) # printando a variavel
print(type(nome)) # printando o tipo da variavel

print(idade)
print(type(idade))

print(altura)
print(type(altura))

print(inf)
print(type(inf))

