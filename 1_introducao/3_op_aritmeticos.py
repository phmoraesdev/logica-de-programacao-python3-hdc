num3 = 13
num4 = 7

resto = num3 % num4  # resto da divisao (13 dividido por 7 sobra 6)
divisao_inteira = num3 // num4  # divisao inteira, descarta a parte decimal (13/7 = 1,85 -> 1)

print(resto)
print(divisao_inteira)