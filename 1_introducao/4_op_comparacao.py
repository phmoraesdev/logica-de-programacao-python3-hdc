# operador de ATRIBUICAO
a = 10
b = 10


# operadores de COMPARACAO comparam dois valores

# "==" operador de IGUALDADE
print(a == b)

# "!=" operador de DIFERENCA
print(a != b)


x = 15
y = 10

# ">" maior que
print(x > y)
print(y > x)

# "<" menor que
print(x < y)
print(y < x)

# ">=" maior ou igual
print(x >= y)
print(x >= 15)

# "<=" menor ou igual
print(y <= x)
print(y <= 10)
